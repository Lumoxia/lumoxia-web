HEADER = "<!-- Generated by scripts/build.py from templates/ and i18n/. Do not edit. -->"
TOKEN = re.compile(r"\{\{([a-z]+)(?::([^}]*))?\}\}")
APP_TOKEN = re.compile(r"\{app:([A-Za-z0-9]+)\}")
LATIN_FONTS = (
    '  <link rel="preconnect" href="https://fonts.googleapis.com" />\n'
    '  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />\n'
    '  <link href="https://fonts.googleapis.com/css2?family=Cinzel:wght@500;600;700&family=Inter:wght@400;500;600&display=swap" rel="stylesheet" />'
)
FONT_FAMILIES = {"arabic": "Noto+Sans+Arabic:wght@400;500;700", "devanagari": "Noto+Sans+Devanagari:wght@400;500;700",
                 "hebrew": "Noto+Sans+Hebrew:wght@400;500;700",
                 "cyrillic": "Noto+Serif:wght@500;600;700&family=Inter:wght@400;500;600"}


class BuildError(Exception):
    pass


@dataclass
class Context:
    strings: dict
    app: dict
    simple: dict = field(default_factory=dict)
    partials: dict = field(default_factory=dict)


def _app(value, ctx, escape):
    def sub(m):
        if m.group(1) not in ctx.app:
            raise BuildError(f"unknown app term {m.group(1)}")
        term = ctx.app[m.group(1)]
        return html.escape(term, quote=False) if escape else term
    return APP_TOKEN.sub(sub, value)


def expand(text, ctx):
    for _ in range(10):
        def sub(m):
            kind, arg = m.group(1), m.group(2)
            if kind in ("t", "attr", "url"):
                if arg not in ctx.strings:
                    raise BuildError(f"missing string key {arg}")
                v = ctx.strings[arg]
                if kind == "t":
                    return _app(v, ctx, True)
                v = _app(v, ctx, False)
                return html.escape(v, quote=True) if kind == "attr" else urllib.parse.quote(v, safe="")
            if kind == "include":
                if arg not in ctx.partials:
                    raise BuildError(f"missing partial {arg}")
                return ctx.partials[arg].rstrip("\n")
            if arg is None and kind in ctx.simple:
                return ctx.simple[kind]
            raise BuildError(f"unknown token {m.group(0)}")
        new = TOKEN.sub(sub, text)
        if new == text:
            return text
        text = new
    raise BuildError("token expansion did not settle")


def rel_prefix(rel, lang_dir=None):
    """Relative path from the page to the root of its language tree."""
    p = Path(rel)
    if lang_dir:
        p = p.relative_to(lang_dir)
    return "../" * (len(p.parts) - 1)


def root_prefix(rel):
    """Relative path from the page to the site root."""
    return "../" * (len(Path(rel).parts) - 1)


def address(code, page_addr):
    return ("/" if code == "en" else f"/{code}/") + page_addr


def image_size(path):
    """Width and height of an SVG (from its viewBox) or PNG (from its header), rounded to whole pixels."""
    data = path.read_bytes()
    if path.suffix == ".png":
        if data[:8] != b"\x89PNG\r\n\x1a\n":
            raise BuildError(f"{path.name} is not a PNG")
        w, h = struct.unpack(">II", data[16:24])
        return w, h
    m = re.search(rb'viewBox="\s*[-\d.]+[ ,]+[-\d.]+[ ,]+([\d.]+)[ ,]+([\d.]+)\s*"', data)
    if not m:
        raise BuildError(f"{path.name} has no viewBox")
    return round(float(m.group(1))), round(float(m.group(2)))


def strip_colon(label):
    return label.rstrip(":\uff1a\u00a0 ").strip()


class Site:
    def __init__(self, root=ROOT):
        self.root = root
        self.languages = json.loads((root / "i18n/languages.json").read_text("utf-8"))
        self.app = json.loads((root / "i18n/app-terms.json").read_text("utf-8"))
        self.strings = {l["code"]: json.loads((root / f"i18n/strings/{l['code']}.json").read_text("utf-8"))
                        for l in self.languages}
        self.templates = {n: (root / "templates" / t).read_text("utf-8") for n, (t, _) in PAGES.items()}
        self.partials = {"partials/head.html": (root / "templates/partials/head.html").read_text("utf-8")}
        self.detect_src = (root / "assets/lang-detect.js").read_text("utf-8")

    def lang(self, code):
        return next(l for l in self.languages if l["code"] == code)

    def render_page(self, code, page):
        lang = self.lang(code)
        _, addr = PAGES[page]
        rel = (f"{code}/" if code != "en" else "") + addr + "index.html" if addr else (f"{code}/" if code != "en" else "") + "index.html"
        lang_dir = None if code == "en" else code
        app = self.app[code]
        button = strip_colon(app["langLabel"])
        simple = {
            "base": rel_prefix(rel, lang_dir), "root": root_prefix(rel), "htmllang": lang["htmlLang"],
            "lang": code, "dir": lang["dir"], "oglocale": lang["ogLocale"],
            "canonical": SITE + address(code, addr),
            "fsclass": "" if lang["fontSet"] == "latin" else f' class="fs-{lang["fontSet"]}"',
            "alternates": self.alternates(addr), "fonts": self.fonts(lang["fontSet"]),
            "detect": self.detect() if code == "en" else "",
            "langmenu": self.langmenu(code, addr, button), "patreon": PATREON_URL,
            "album": ALBUM_TITLE,
            "albumlinks": self.albumlinks(code, root_prefix(rel)) if page == "index" else "",
        }
        strings = dict(self.strings[code])
        ctx = Context(strings=strings, app=app, simple=simple, partials=self.partials)
        out = expand(self.templates[page], ctx)
        out = out.replace("\n\n\n", "\n\n")
        out = re.sub(r"\n[ \t]*\n(?=</head>)", "\n", out)
        first, rest = out.split("\n", 1)
        return first + "\n" + HEADER + "\n" + rest.rstrip("\n") + "\n", rel

    def logo_path(self, service, code):
        """The logo file for a service in a language (Apple's badge is localised, with an English fallback)."""
        name = service["file"].replace("{lang}", code)
        if not (self.root / "assets/music" / name).is_file():
            name = service["file"].replace("{lang}", "en")
        path = self.root / "assets/music" / name
        if not path.is_file():
            raise BuildError(f"missing logo file assets/music/{name}")
        return name, path

    def albumlinks(self, code, root):
        """One centred list of logo links per row of MUSIC_SERVICES."""
        strings = self.strings[code]
        rows = []
        for row in MUSIC_ROWS:
            items = []
            for svc in (s for s in MUSIC_SERVICES if s["row"] == row):
                name, path = self.logo_path(svc, code)
                w, h = image_size(path)
                label = strings["music.link"].replace("{{album}}", ALBUM_TITLE).replace("{service}", svc["name"])
                items.append(
                    f'    <li class="svc-{svc["key"]}"><a href="{html.escape(svc["url"], quote=True)}" target="_blank" rel="noopener" '
                    f'aria-label="{html.escape(label, quote=True)}"><img src="{root}assets/music/{name}" alt="" '
                    f'width="{w}" height="{h}" loading="lazy" /></a></li>')
            if items:
                cls = "listen" if row == "main" else f"listen listen-{row}"
                rows.append(f'<ul class="{cls}" aria-label="{html.escape(strings["music.links.label"], quote=True)}">\n'
                            + "\n".join(items) + "\n</ul>")
        return "\n".join(rows)

    def alternates(self, addr):
        lines = [f'  <link rel="alternate" hreflang="{l["htmlLang"]}" href="{SITE}{address(l["code"], addr)}" />'
                 for l in self.languages]
        lines.append(f'  <link rel="alternate" hreflang="x-default" href="{SITE}{address("en", addr)}" />')
        return "\n".join(lines)

    def fonts(self, font_set):
        if font_set == "latin":
            return LATIN_FONTS
        # Cinzel stays for the LUMOXIA wordmark; the script's own family covers the text
        families = "Cinzel:wght@500;600;700"
        if font_set in FONT_FAMILIES:
            families += "&family=" + FONT_FAMILIES[font_set]
        return ('  <link rel="preconnect" href="https://fonts.googleapis.com" />\n'
                '  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />\n'
                f'  <link href="https://fonts.googleapis.com/css2?family={families}&display=swap" rel="stylesheet" />')

    def detect(self):
        codes = json.dumps([l["code"] for l in self.languages]).replace(", ", ",")
        src = self.detect_src.strip().replace("\n", "\n  ")
        return (
            "  <script>\n  " + src + "\n"
            "  (function () {\n"
            "    var saved = null;\n"
            "    try { saved = localStorage.getItem('lumoxia.lang'); } catch (e) {}\n"
            f"    var r = lumoxiaDetect(saved, location.search, navigator.languages || [navigator.language || 'en'], {codes});\n"
            "    if (r.save) { try { localStorage.setItem('lumoxia.lang', r.save); } catch (e) {} }\n"
            "    if (r.target && r.target !== 'en') location.replace('/' + r.target + location.pathname + location.hash);\n"
            "  })();\n"
            "  </script>")

    def langmenu(self, code, addr, button):
        current = self.lang(code)
        items = []
        for l in self.languages:
            href = address(l["code"], addr) + ("?lang=en" if l["code"] == "en" else "")
            cur = ' aria-current="true"' if l["code"] == code else ""
            items.append(
                f'        <li><a class="lang-option"{cur} href="{href}" hreflang="{l["htmlLang"]}" lang="{l["htmlLang"]}" data-lang="{l["code"]}">'
                f'<span class="lang-chip" aria-hidden="true">{html.escape(l["short"])}</span><span>{html.escape(l["label"])}</span></a></li>')
        label = html.escape(button, quote=True)
        return ('      <details class="lang" data-lang-menu>\n'
                f'        <summary class="lang-button" aria-label="{label}" title="{label}"><span aria-hidden="true">{html.escape(current["short"])}</span></summary>\n'
                '        <ul class="lang-list">\n' + "\n".join(items) + "\n        </ul>\n      </details>")

    def sitemap(self):
        out = ['<?xml version="1.0" encoding="UTF-8"?>',
               '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
        for _, addr in PAGES.values():
            for l in self.languages:
                out.append("  <url>")
                out.append(f"    <loc>{SITE}{address(l['code'], addr)}</loc>")
                for m in self.languages:
                    out.append(f'    <xhtml:link rel="alternate" hreflang="{m["htmlLang"]}" href="{SITE}{address(m["code"], addr)}"/>')
                out.append(f'    <xhtml:link rel="alternate" hreflang="x-default" href="{SITE}{address("en", addr)}"/>')
                out.append("  </url>")
        out.append("</urlset>")
        return "\n".join(out) + "\n"

    def render_all(self):
        files = {}
        for l in self.languages:
            for page in PAGES:
                text, rel = self.render_page(l["code"], page)
                files[rel] = text
        files["sitemap.xml"] = self.sitemap()
        return files


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    files = Site().render_all()
    if args.check:
        bad = [p for p, t in files.items() if not (ROOT / p).exists() or (ROOT / p).read_text("utf-8") != t]
        for p in bad:
            print("STALE OR MISSING:", p)
        print("generated pages:", "OUT OF DATE, run python3 scripts/build.py" if bad else "up to date")
        return 1 if bad else 0
    for p, t in files.items():
        f = ROOT / p
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(t, "utf-8")
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
